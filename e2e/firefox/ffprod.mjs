import { launchFF, extPage, startProxy } from "./fflib.mjs";
import { shadow, until, people, check, summary, out, sleep, keyOf } from "/workspace/work/e2e/lib.mjs";
import net from "node:net";
const FAKE = new Set(["www.netflix.com", "www.hotstar.com", "www.jiohotstar.com", "www.youtube.com"]);
const p = startProxy();
p.removeAllListeners("connect");
p.on("connect", (req, sock, head) => {
  const [host, port] = req.url.split(":");
  const real = ["netparty.tech", "static.klipy.com", "static1.klipy.com", "static2.klipy.com"].includes(host);
  if (!real && !FAKE.has(host)) return sock.end("HTTP/1.1 403 Forbidden\r\n\r\n");
  const up = real ? net.connect(Number(port) || 443, host) : net.connect(8443, "127.0.0.1");
  up.on("connect", () => { sock.write("HTTP/1.1 200 Connection Established\r\n\r\n"); up.write(head); up.pipe(sock); sock.pipe(up); });
  up.on("error", () => sock.destroy()); sock.on("error", () => up.destroy());
});
const H = await launchFF("/tmp/ff-prod-h", { uuid: "aaaaaaaa-0000-4000-8000-000000000008" });
const G = await launchFF("/tmp/ff-prod-g", { uuid: "aaaaaaaa-0000-4000-8000-000000000009" });
const he = await extPage(H), ge = await extPage(G);
check("default server is wss://netparty.tech", (await he.evaluate(() => chrome.storage.sync.get("serverUrl"))).serverUrl === "wss://netparty.tech");
await he.evaluate(() => chrome.storage.sync.set({ name: "FoxHost" })); await ge.evaluate(() => chrome.storage.sync.set({ name: "FoxGuest" }));
const hp = await H.browser.newPage(), gp = await G.browser.newPage();
