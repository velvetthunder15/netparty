check("party created on netparty.tech from Firefox", /^https:\/\/netparty\.tech\/j\/[a-z0-9]+#k=/.test(created?.invite || "") && !!keyOf(created.invite), JSON.stringify(created).replace(/#k=[\w-]+/, "#k=…"));
