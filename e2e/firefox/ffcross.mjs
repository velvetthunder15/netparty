// Mixed party: Firefox (AMO build) hosts, Chromium (Chrome build from extension/) joins via the invite link.
process.env.NODE_TLS_REJECT_UNAUTHORIZED = "0";
import { launchFF, extPage, tapTLS } from "./fflib.mjs";
import { launch, shadow, until, people, check, summary, out, sleep, keyOf, leaks } from "/workspace/work/e2e/lib.mjs";
const T = tapTLS(8792, 8787);
const H = await launchFF("/tmp/ff-cross", { uuid: "aaaaaaaa-0000-4000-8000-000000000006" });
const he = await extPage(H);
await he.evaluate((u) => chrome.storage.sync.set({ serverUrl: u, name: "Foxy" }), T.url);
const G = await launch("/tmp/pw-cross", { name: "Chromy", extra: { serverUrl: T.url } });
const hp = await H.browser.newPage();
await hp.goto("https://www.netflix.com/watch/12345", { waitUntil: "domcontentloaded" });
await sleep(2500);
await hp.bringToFront();
const created = await he.evaluate(async () => { const tabs = await chrome.tabs.query({}); const t = tabs.find((t) => /netflix/.test(t.url || "")); return chrome.tabs.sendMessage(t.id, { cmd: "create" }); });
check("Firefox host created a party", !!keyOf(created?.invite), JSON.stringify(created));
const gp = await G.ctx.newPage();
await gp.goto(created.invite);
await until(async () => /invited you/.test(await gp.textContent("h1")), 6000);
await Promise.all([gp.waitForNavigation(), gp.click("a.btn")]);
check("Chromium guest joined the Firefox host's party", !!(await until(async () => (await people(gp)).length === 2, 20000)), JSON.stringify(await people(gp)));
check("names decrypt across browsers", JSON.stringify(await people(gp)) === '["Foxy","You"]' && !!(await until(async () => JSON.stringify(await people(hp)) === '["You","Chromy"]', 6000)), JSON.stringify([await people(gp), await people(hp)]));
const bubbles = (p) => shadow(p, (r) => { return [...r.querySelectorAll(".np-bubble")].map((n) => n.firstChild.textContent); });
await gp.evaluate(() => document.getElementById("netparty-root").shadowRoot.querySelector(".np-input").focus());
await gp.keyboard.type("chromium says hi XMARK");
await gp.keyboard.press("Enter");
check("chat Chromium → Firefox", !!(await until(async () => (await bubbles(hp))?.includes("chromium says hi XMARK"))));
await hp.evaluate(() => document.getElementById("netparty-root").shadowRoot.querySelector(".np-input").focus());
await hp.keyboard.type("firefox says hi XMARK");
await hp.keyboard.press("Enter");
check("chat Firefox → Chromium", !!(await until(async () => (await bubbles(gp))?.includes("firefox says hi XMARK"))));
const ffFont = async (p) => { try { return await p.evaluate(async () => { await document.fonts.ready; return [...document.fonts].some((f) => f.family.replace(/"/g, "") === "NetParty Inter" && f.status === "loaded"); }); } catch { return false; } };
check("Inter font loads in Firefox", !!(await until(() => ffFont(hp), 8000)));
check("Inter font loads in Chromium (guest)", !!(await until(() => ffFont(gp), 8000)));
await hp.evaluate(() => { const v = document.querySelector("video"); v.currentTime = 50; v.play(); });
await sleep(3000);
const a = await hp.evaluate(() => document.querySelector("video").currentTime), b = await gp.evaluate(() => document.querySelector("video").currentTime);
check("sync Firefox → Chromium (seek 50 s)", Math.abs(a - b) < 1.5, `${a.toFixed(1)} vs ${b.toFixed(1)}`);
await gp.evaluate(() => document.querySelector("video").pause());
check("sync Chromium → Firefox (pause)", !!(await until(() => hp.evaluate(() => document.querySelector("video").paused), 6000)));
const linked = (p) => shadow(p, (r) => { return [...r.querySelectorAll(".np-person[data-link]")].map((n) => n.dataset.link).join(); });
await shadow(gp, (r) => { r.querySelector(".np-join-voice")?.click(); });
await sleep(700);
await shadow(hp, (r) => { r.querySelector(".np-join-voice")?.click(); });
check("voice connects Firefox ↔ Chromium", !!(await until(async () => (await linked(hp)) === "connected" && (await linked(gp)) === "connected", 25000)), JSON.stringify([await linked(hp), await linked(gp)]));
// 1.8 video chat across browsers (Firefox offered the connection, so it made the video slot)
const tiles = (p) => shadow(p, (r) => { const c = r.querySelector(".np-cams"); return !c || c.hidden ? [] : [...c.querySelectorAll(".np-cam")].map((t) => { const v = t.querySelector("video"); return { name: t.querySelector(".np-cam-name").textContent, w: v.videoWidth, t: v.currentTime, live: !t.classList.contains("np-cam-wait") }; }); });
const liveTile = async (p, name) => { const a = (await tiles(p)).find((x) => x.name === name); await sleep(800); const b = (await tiles(p)).find((x) => x.name === name); return a && b && b.live && b.w > 0 && b.t > a.t ? b : null; };
await shadow(hp, (r) => { r.querySelector(".np-cam-btn").click(); });
check("Firefox camera → Chromium sees a live tile", !!(await until(() => liveTile(gp, "Foxy"), 20000, 500)), JSON.stringify(await tiles(gp)));
await shadow(gp, (r) => { r.querySelector(".np-cam-btn").click(); });
check("Chromium camera → Firefox sees a live tile", !!(await until(() => liveTile(hp, "Chromy"), 20000, 500)), JSON.stringify(await tiles(hp)));
await shadow(hp, (r) => { r.querySelector(".np-cam-btn").click(); });
check("Firefox camera off → its tile leaves Chromium", !!(await until(async () => !(await tiles(gp)).some((t) => t.name === "Foxy"), 8000)));
check("no SDP / camera state in any frame", leaks(T.frames, ["m=video", "a=fingerprint", '"cam"']).length === 0);
check("no names/messages/key in any frame", leaks(T.frames, ["Foxy", "Chromy", "XMARK", keyOf(created.invite)]).length === 0);
const f = summary("CROSS-BROWSER");
await H.browser.close(); await G.ctx.close(); T.close();
process.exit(f ? 1 : 0);
