// Generates the emoji search names in extension/emoji-data.js (the block between the
// "<names>" markers) from Unicode CLDR English annotations: the short name plus a few keywords.
// Run when the bundled emoji list changes:  node scripts/gen-emoji-names.mjs
// Needs network access once (raw.githubusercontent.com); the extension never fetches anything.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const FILE = path.join(here, "../extension/emoji-data.js");
const BASE = "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json";
const SOURCES = [
  `${BASE}/cldr-annotations-full/annotations/en/annotations.json`,
  `${BASE}/cldr-annotations-derived-full/annotationsDerived/en/annotations.json`,
];
const MAX_KEYWORDS = 12;

const ann = {};
for (const url of SOURCES) {
  const j = await (await fetch(url)).json();
  Object.assign(ann, (j.annotations || j.annotationsDerived).annotations);
}
const strip = (e) => e.replace(/\uFE0F/g, "");
const byStripped = new Map(Object.entries(ann).map(([k, v]) => [strip(k), v]));

const src = fs.readFileSync(FILE, "utf8");
globalThis.NP_EMOJI = undefined;
new Function(src.replace(/\/\/ <names>[\s\S]*\/\/ <\/names>\n?/, ""))();
const all = new Set([...NP_EMOJI.categories.flatMap((c) => c.list), ...NP_EMOJI.avatars, ...NP_EMOJI.reactions]);

const names = {};
const missing = [];
for (const e of all) {
  const a = ann[e] || byStripped.get(strip(e));
  if (!a) {
    missing.push(e);
    continue;
  }
  const tts = (a.tts?.[0] || "").toLowerCase().replace(/[^\p{L}\p{N}' &-]+/gu, " ").replace(/\s+/g, " ").trim();
  const words = new Set(tts.split(/\s+/));
  const kws = (a.default || [])
    .map((k) => k.toLowerCase().trim())
    .filter((k) => k && !/[|]/.test(k) && !words.has(k) && k !== tts)
    .slice(0, MAX_KEYWORDS);
  names[e] = [tts, ...kws].join("|");
}
if (missing.length) console.warn("no CLDR annotation for:", missing.join(" "));

const block =
  "// <names>\n" +
  "  // search names: CLDR short name, then keywords, \"|\"-separated (generated by scripts/gen-emoji-names.mjs)\n" +
  "  globalThis.NP_EMOJI.names = {\n" +
  Object.entries(names).map(([e, n]) => `    ${JSON.stringify(e)}: ${JSON.stringify(n)},`).join("\n") +
  "\n  };\n  // </names>\n";
let out;
if (/\/\/ <names>[\s\S]*\/\/ <\/names>\n?/.test(src)) out = src.replace(/\/\/ <names>[\s\S]*\/\/ <\/names>\n?/, block.trimStart());
else out = src.replace(/\n\}\)\(\);\s*$/, "\n  " + block + "})();\n");
fs.writeFileSync(FILE, out);
console.log(`${Object.keys(names).length} names written to ${path.relative(process.cwd(), FILE)} (${out.length} bytes)`);
